export function isSiteSlug(value: string): value is SiteSlug {
  return SITE_LINKS.some((link) => link.slug === value);
}

export function sectionId(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^a-zа-яё0-9]+/gi, "-")
    .replace(/^-+|-+$/g, "");
}

